"""답변이 **어느 모델로 만들어졌는지** — 화면에 낼 수 있는 형태로 (#226).

## 왜 이 축이 있나

설정에 제공자 축이 없고 모델명만 있다(`ROUTER_LLM_MODEL`·`GENERATOR_LLM_MODEL`). 게이트웨이가
모델명으로 제공자를 간접 지정하므로, 받은 사람은 자기 키가 어느 제공자 것인지에 따라 무엇을
적어야 하는지 모르고, 잘못 적어도 **기동은 되고 질문할 때 터진다.**

제공자를 고르는 화면은 키 저장 방침이 정해져야 만들 수 있다(#225 결정 대기). 그 전에도
**지금 무슨 모델이 답했는지**는 낼 수 있고, 그것만으로도 「내가 넣은 설정이 실제로 쓰였나」가
확인된다. 이 레포가 이미 세운 축(`grounding` 정직 라벨 · 「화면의 모든 숫자가 출처를 갖는다」)과
같은 자리다.

## 경계

**호출하지 않는다.** 설정에 적힌 값을 읽어 옮길 뿐이다 — 실제로 그 모델이 응답했는지는 이
함수가 알 수 없고, 확인 호출은 #225 의 「연결 확인」이 맡는다. 그래서 이름도 「무엇으로
답하도록 설정돼 있나」이지 「무엇이 답했나」가 아니다.
"""

from __future__ import annotations

from typing import Any

#: 게이트웨이 URL 로 제공자를 추정하지 않는다 — 사내 게이트웨이는 어느 제공자든 감싸므로
#: 추정이 틀리면 화면이 거짓을 말한다. 모르는 것은 모른다고 낸다.
UNKNOWN = "설정되지 않음"


def model_identity(config: Any) -> dict[str, str]:
    """계획·답변에 쓰이는 모델 이름. 값이 비면 「설정되지 않음」으로 낸다."""
    return {
        "planner": (getattr(config, "ROUTER_LLM_MODEL", "") or UNKNOWN),
        "generator": (getattr(config, "GENERATOR_LLM_MODEL", "") or UNKNOWN),
    }
