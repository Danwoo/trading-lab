# ── 공백 처리 — 「브라우저가 실제로 하는 것」과 글자 단위로 맞춘다 (#406 ① 재수정, PR #409 리뷰) ──
# 페이로드에서 공백을 배제하면 **MIME 표준 76컬럼 wrap 한 줄로 규칙 A·B 가 전부 뚫린다** —
# 리뷰가 실제 트리 자산(`frontend/public/logo.png`, 15106 B)으로 위반 1건 → 0건을 실측했다.
# 브라우저는 그 줄바꿈을 지우고 원본 바이트를 그대로 되살리므로, 게이트도 같은 것을 지운 뒤
# 디코드해야 한다. **벗기는 문자 집합은 임의로 고르지 않고 WHATWG 가 벗기는 것과 맞춘다:**
#
#   · **base64 페이로드 — 5종 전부.** forgiving-base64 decode 가 「ASCII whitespace 를 전부
#     제거」한다. WHATWG Infra 의 ASCII whitespace = U+0009 TAB · U+000A LF · U+000C FF ·
#     U+000D CR · U+0020 SPACE. (앞단 URL 파서는 tab·LF·CR 만 지우지만, 남은 SPACE·FF 는
#     opaque path 에서 `%20`·`%0C` 로 퍼센트 인코딩됐다가 data: URL processor 의 퍼센트
#     디코딩으로 되살아나고, 그 뒤 forgiving-base64 가 마저 지운다 → 순효과가 5종 전부다.)
#   · **퍼센트 인코딩 페이로드 — 3종만.** base64 단계가 없으니 URL 파서가 URL 전체에서 지우는
#     「ASCII tab or newline」(U+0009 · U+000A · U+000D)뿐이다. SPACE·FF 는 내용으로 남는다 —
#     SVG 의 좌표 구분 공백처럼 **의미 있는 바이트**라 여기서 지우면 내용이 바뀐다.
#
# **`\s` 를 쓰지 않는다.** `\s` 는 U+00A0·U+2028 같은 유니코드 공백까지 먹어 브라우저 동작과
# 어긋난다 — 넓게 잡는 쪽이라도 「브라우저가 되살리는 형태」라는 이 검사의 기준선이 흐려진다.
B64_STRIP_CHARS = "\t\n\f\r "
URL_STRIP_CHARS = "\t\n\r"


def _char_class(chars: str, extra: str = "") -> str:
    """정규식 문자 클래스 — 위 상수에서 **유도**한다 (손으로 옮겨 적으면 두 벌이 갈린다).

    내용이 비면 `[]` 는 정규식 문법 오류라 모듈이 import 단계에서 죽는다. 상수를 비우는 것은
    설정 실수이지 문법 사고로 보일 일이 아니므로, **아무것도 매치하지 않는** 클래스로 떨어뜨려
    「공백을 안 벗기던 시절의 동작」이 되게 한다 (BARE_B64_RE 의 앵커 0개 처리와 같은 모양).
    """
    body = extra + "".join(f"\\x{ord(c):02x}" for c in chars)
    return "[" + body + "]" if body else r"[^\s\S]"


def _ws_tolerant(literal: str, chars: str) -> str:
    """리터럴의 **글자 사이마다** `chars` 의 공백을 허용하는 패턴.

    **어느 집합을 넘기느냐가 층을 가른다.** base64 페이로드·D2 앵커는 forgiving-base64 가
    지우는 5종(`B64_STRIP_CHARS`), `data:` 스킴·마임 구간은 URL 파서가 지우는 3종
    (`URL_STRIP_CHARS`)이다. 집합을 함수 안에 박아 두면 한쪽 층의 규칙이 다른 층으로 새므로
    인자로 받는다 (실제로 종전에는 `;base64,` 표시가 base64 층 집합을 쓰고 있었다).

    wrap 위치가 앵커 한가운데를 잘라도(`iVBO\\nRw0K`) D2 가 놓치지 않게 한다 — 76컬럼 같은
    표준 폭은 앵커를 안 자르지만 임의 위치 개행은 자른다.
    """
    return (_char_class(chars) + "*").join(re.escape(ch) for ch in literal)


_B64_BODY = _char_class(B64_STRIP_CHARS, "A-Za-z0-9+/")

# base64 페이로드의 한 조각 — 글자·공백 **또는 `%XX`**.
# data: URL processor 는 **퍼센트 디코딩을 base64 디코딩보다 먼저** 한다. 그래서 `%0A`·`%20`
# 으로 적은 공백도 브라우저에선 사라진다 (자체 공격 실측: 이 자리를 안 보면 `%0A` 한 개로
# 규칙 A·B 가 다시 뚫린다). **`%` 를 통째로 허용하지 않고 `%XX` 형태일 때만** 받는 이유:
# 통째로 허용하면 엉뚱한 `%` 하나가 페이로드에 붙어 디코드가 실패하고, 종전에 잡히던 것이
# 조용히 안 잡히게 된다 (매치가 `%` 에서 끊기던 동작을 보존한다).
_B64_ATOM = r"(?:" + _B64_BODY + r"|%[0-9A-Fa-f]{2})"

