def _svg_marker_found(data: bytes) -> bool:
    """SVG 마커가 payload **어디에든** 있나 — 위치도 앞에 붙은 바이트도 보지 않는다.

    ## 왜 「위치를 안 보는가」 — 종전 두 방식이 같은 뿌리에서 뚫렸다 (PR #409 3라운드)

    이 판정은 두 번 고쳐졌고 두 번 다 **「자산의 시작점을 알아맞히는」 방식**이었다:

      · **창** (`data[:512]`, `<?xml` 이면 `data[:4096]`) — XML 은 루트 앞 주석을 크기 제한
        없이 허용해서, 주석 한 덩어리로 마커가 창 밖으로 밀려났다 (kimi CI 리뷰 발견 3).
      · **프롤로그 건너뛰기** (`_xml_root_offset` — 삭제됨) — 창 대신 프롤로그를 실제로
        건너뛰고 그 위치에서 `<` 를 **요구**했다. 진입점이 `data.lstrip()` 이었는데 이것은
        **파이썬 기본 ASCII 공백만** 벗기므로, **선두 바이트 하나**(UTF-8 BOM `EF BB BF` ·
        NUL · NEL U+0085 · NBSP · ZWSP · 그 밖의 C0 제어문자 · 심지어 글자 `x` 하나)로
        오프셋이 0 에 묶이고 `<` 요구가 깨져 **스니핑이 통째로 죽었다.** D1 의 base64 판과
        퍼센트 판이 함께 뚫렸다.

    두 번째 방식을 살리려면 「루트 앞에 올 수 있는 바이트」를 **열거**해야 하는데, 그 목록은
    닫히지 않는다 — BOM 을 넣으면 NUL 이 남고, NUL 을 넣으면 NEL 이 남는다. 이번 PR 에서
    열거 접근은 이미 두 번 실패했다 (`_MIME_SPAN` 200자 상한 → 제거, 스킴 공백 → 층 분리).
    그래서 **시작점을 알아맞히기를 그만둔다**: 마커가 payload 안에 있으면 자산으로 본다.
    상수도 없고 벗길 것을 열거하지도 않으므로 「그만큼 패딩하면 다시 뚫린다」가 성립하지 않는다.

    ## 대신 무엇을 내주나 — 오탐 (실측)

    「루트가 svg 인가」라는 정밀도를 버리고 「어딘가에 `<svg` 가 있는가」로 넓혔다. 트리의
    **모든 파일을 통째로 인라인한 최악 가정**으로 잰 오탐 비용 (2026-08-05, 1016파일):

        판정 규칙                        SVG 로 잡히는 파일
        종전 (512창 + 프롤로그 루트)              3
        창 4096 탐색                          8
        창 65536 탐색                        14
        창 무제한 탐색 (지금 — 이 함수)            14

    무제한이 종전보다 새로 잡는 11파일 중 **8개는 `frontend/` 컴포넌트의 진짜 JSX SVG 아트워크**다 —
    그것을 data: URI 로 인라인하면 잡히는 게 맞다(#360 이 막는 클래스 그 자체). 나머지 3개는
    이 게이트와 그 문서·테스트로, `<svg` 를 **설명하는 산문**이라 오탐이다. 그리고 유한한 창은
    오탐을 줄여 주지도 않는다 — 64 KiB 창의 오탐이 무제한과 같으면서 패딩 상수만 되살린다.
    **실제 트리 스캔에서 이 변경으로 새로 생기는 위반은 0건이다** (디코드까지 성공하는 조각
    자체가 트리에 1건뿐이고 자산이 아니다 — 모듈 독스트링 실측 (c)·(d)).

    오탐은 **릴리스를 멈추는 방향**이고 미탐은 자산을 내보내는 방향이라, 이 교환은 감수한다.

    ## UTF-16·UTF-32 (NUL 패딩) — 인코딩을 열거하지 않고 받는다

    UTF-16/32 로 인코딩된 XML 은 ASCII 글자 사이에 NUL 이 낀다 (`<\\x00s\\x00v\\x00g`).
    BOM 표를 만들어 인코딩별로 디코드하는 것은 또 하나의 열거라, **NUL 을 지운 판**에서도
    같은 마커를 본다 — LE·BE, BOM 유무, UTF-16·UTF-32 를 한 줄로 함께 받는다. 못 받는 것은
    NUL 패딩이 아닌 비 ASCII 호환 인코딩(EBCDIC·UTF-7 의 `+ADw-` 표기)이고, 모듈 독스트링
    「못 막는 것」에 적었다.

    ## 비용 (실측 2026-08-05, 3회 최솟값)

        payload                       종전       지금
        SVG 2.5 KiB (주석 프롤로그)     0.025 ms   0.006 ms   ← lstrip 전체 복사가 없어져 더 빠르다
        PNG 1 MiB                    0.001 ms   0.001 ms   ← 매직에서 즉시 확정 (변화 없음)
        텍스트 8 MiB (마커 없음)         2.5 ms     9.6 ms
        UTF-16 8 MiB (NUL 낀 판)      3.3 ms   118.8 ms   ← NUL 제거 복사가 지배한다

    전부 payload 길이에 **선형**이고, 한 파일의 디코드 총량은 파일 길이에 묶인다. 트리 전수
    실행(1016파일 23.5 MiB)은 종전 4.99 s → 지금 5.08 s 로 **잡음 범위 안**이다 (교대 6회
    최솟값. 이 스크립트의 시간은 파일당 `git cat-file` 이 지배한다).
    재현: `python3 scripts/verify_public_release_tree.py`
    """
    if SVG_MARKER.search(data):
        return True
    return b"\x00" in data and SVG_MARKER.search(data.replace(b"\x00", b"")) is not None


def sniff_asset(data: bytes) -> str | None:
    """디코드된 바이트가 자산이면 그 종류 이름, 아니면 None.

    **선언된 mime 은 쓰지 않는다** — `data:text/plain;base64,<PNG>` 로 라벨만 바꾸는 우회가
    있기 때문이다. 판정은 오직 내용이다: 매직 넘버 일치 · SVG 마커 · 「UTF-8 로 안 읽힘」.
    """
    magic_name = sniff_magic(data)
    if magic_name:
        return magic_name
    if _svg_marker_found(data):
        return SVG_ASSET_KIND
    if not is_text(data):
        return "바이너리 (매직 넘버 미상)"
    return None


def strip_chars(text: str, chars: str) -> str:
    """`chars` 에 있는 글자를 **전부** 지운다 (양끝이 아니라 안쪽까지 — WHATWG 의 「remove all」)."""
    return text.translate({ord(c): None for c in chars})


def _decode_b64(payload: str, minimum: int = MIN_B64_PAYLOAD_CHARS) -> bytes | None:
    """브라우저와 **같은 순서로** 푼다 — 퍼센트 디코딩 → 공백 제거 → base64 디코딩.

    순서가 이유가 있다: data: URL processor 는 본문을 percent-decode 한 뒤(그 결과를 isomorphic
    decode 로 문자열로 되돌린 다음) forgiving-base64 로 디코드한다. 그래서 `%0A` 로 적은
    줄바꿈도 최종적으로는 사라진다 (#406 ① 재수정 — 위 「공백 처리」 주석이 근거).

    최소 길이는 **공백을 뺀 실제 base64 글자 수**로 잰다. 정규식의 `{16,}` 는 공백까지 세므로
    그것만 믿으면 「공백 15개 + 글자 1개」가 통과한다.
    """
    payload = urllib.parse.unquote_to_bytes(payload).decode("latin-1")  # = isomorphic decode
    payload = strip_chars(payload, B64_STRIP_CHARS)
    if len(payload) < minimum:
        return None
    padded = payload + "=" * (-len(payload) % 4)
    try:
        return base64.b64decode(padded, validate=True)
    except (binascii.Error, ValueError):
        return None


def _data_scheme_start(text: str, boundary: int) -> int | None:
    """`boundary` 앞이 `data:` URI 의 메타데이터 구간이면 그 `data:` 의 시작 위치.

    메타데이터 구간(스킴~본문 사이)은 **콤마를 담지 못한다** — data: URL 은 첫 콤마에서 본문이
    시작하기 때문이다. 그래서 바로 앞 콤마까지만 되짚으면 충분하고, 후보마다 되짚는 거리를
    모두 합쳐도 파일 길이를 넘지 않아 **비용이 선형으로 묶인다.** 종전의 200자 상한이 하던
    일을 **탐지를 줄이지 않고** 대신하는 자리다 (위 「표시 앵커」 주석이 근거).

    스킴 키워드의 공백은 URL 층 집합(tab·LF·CR)으로만 받는다 — SPACE·FF 는 URL 파서가 안
    지우고 퍼센트 인코딩으로 남겨 스킴이 깨진다(브라우저도 못 되살리므로 받으면 오탐이다).
    """
    segment_start = text.rfind(",", 0, boundary) + 1
    found = _DATA_SCHEME_RE.search(text, segment_start, boundary)
    return found.start() if found else None


def _data_uri_bodies(text: str) -> list[tuple[int, int]]:
    """`data:` URI 의 (스킴 시작, 본문 시작) 목록 — 본문은 **첫 콤마 다음 글자**부터다.

    메타데이터 구간은 data: URL 의 정의상 콤마를 담지 못하므로(첫 콤마에서 본문이 시작한다)
    `data:` 뒤 첫 콤마가 본문의 시작을 정한다. **페이로드의 생김새로 후보를 거르지 않는다** —
    그 거름이 이 게이트의 미탐 뿌리였다 (위 「페이로드의 끝」 주석).

    비용: 콤마 위치를 파일당 한 번만 모아 이분 탐색한다. 콤마마다 뒤로 되짚는 방식은
    `data:` 가 콤마 없이 반복되는 입력에서 2차가 되고, `data:` 마다 앞으로 훑는 방식은
    콤마가 멀 때 2차가 된다 — 둘 다 피한다 (O(n log n)).
    """
    schemes = [m.start() for m in _DATA_SCHEME_RE.finditer(text)]
    if not schemes:
        return []
    commas = [m.start() for m in _COMMA_RE.finditer(text)]
    if not commas:
        return []
    # 본문 시작 → 가장 이른 스킴 시작 (같은 본문을 두 번 세지 않는다)
    bodies: dict[int, int] = {}
    for scheme in schemes:
        index = bisect.bisect_right(commas, scheme)
        if index >= len(commas):
            break  # 이 스킴 뒤에 콤마가 없으면 더 뒤의 스킴에도 없다
        bodies.setdefault(commas[index] + 1, scheme)
    return sorted((scheme, body) for body, scheme in bodies.items())


def _payload_end(text: str, scheme: int, body: int, unterminated: dict[str, int]) -> int:
    """페이로드가 끝나는 위치 — **컨테이너가 닫히는 자리**다 (위 「페이로드의 끝」 주석).

    컨테이너를 알아본 경우 **본문을 여는 콤마가 그 컨테이너 안에 있어야** 한다. 밖이면 그
    `data:` 는 이 문자열의 URI 가 아니다 — 문서·주석의 인라인 코드 조각(백틱으로 감싼 `data:`)이
    한참 뒤의 무관한 콤마와 짝지어져 산문을 통째로 페이로드로 삼는 것을 이 조건이 막는다
    (실측: 이 조건이 없으면 현재 트리에서 오탐 위반 1건이 난다 — 게이트 회귀 그물 파일).

    `unterminated` 는 「이 닫는 글자는 여기서부터 찾아도 없다」를 기억한다. 한 번 못 찾았으면
    더 뒤에서도 못 찾으므로, 닫히지 않은 따옴표가 많은 파일에서 매 후보마다 파일 끝까지
    훑는 2차 비용을 없앤다 (닫는 글자 종류가 4개뿐이라 전체 추가 비용은 파일 길이의 4배 이하).
    """
    cursor = scheme - 1
    while cursor >= 0 and text[cursor] in _CONTAINER_GAP_CHARS:
        cursor -= 1
    closer = _CONTAINER_CLOSERS.get(text[cursor]) if cursor >= 0 else None
    if closer is not None:
        blocked = unterminated.get(closer)
        if blocked is not None and scheme >= blocked:
            return -1  # 닫히지 않은 컨테이너 — 브라우저도 문자열로 못 읽는다
        end = text.find(closer, scheme)
        if end < 0:
            unterminated[closer] = scheme
            return -1
        return end if end >= body else -1  # 콤마가 컨테이너 밖이면 이 문자열의 URI 가 아니다
    # 컨테이너를 못 알아본 자리 — 종전의 보수적 문자군으로 끊는다.
    stop = _BARE_TERMINATOR_RE.search(text, body)
    return stop.start() if stop else len(text)


def find_inline_assets(text: str) -> list[tuple[int, str, bytes]]:
    """텍스트 안의 인라인 자산 후보를 (줄 번호, 탐지기 이름, 디코드된 바이트) 로 돌려준다.

    D1(`data:` URI)과 D2(감싸개 없는 base64 런)는 겹칠 수 있다 — 같은 위치의 같은 내용은
    한 번만 돌려준다 (같은 위반이 두 줄로 보고되지 않게).
    """
    found: list[tuple[int, str, bytes]] = []
    seen: set[tuple[int, str]] = set()
    # 줄 번호는 개행 위치를 **한 번만** 모아 이분 탐색한다. 후보마다 `text.count("\n", 0, …)`
    # 를 부르면 후보 수 × 파일 길이가 되어 2차가 된다 — 페이로드를 컨테이너 경계까지 넓히면서
    # 후보 수가 늘자 합성 입력(1 MiB·후보 4만)에서 3.8 s 로 터졌다 (자체 공격 실측).
    newlines: list[int] | None = None

    def add(offset: int, detector: str, data: bytes | None) -> None:
        nonlocal newlines
        if not data:
            return
        if newlines is None:
            newlines = [m.start() for m in _NEWLINE_RE.finditer(text)]
        digest = hashlib.sha1(data).hexdigest()
        line = bisect.bisect_left(newlines, offset) + 1
        if (line, digest) in seen:
            return
        seen.add((line, digest))
        found.append((line, detector, data))

    for match in DATA_URI_B64_RE.finditer(text):
        scheme = _data_scheme_start(text, match.start())
        if scheme is None:
            continue
        add(scheme, "data: URI (base64)", _decode_b64(match.group("payload")))
    # base64 가 아닌 본문 — 퍼센트·원문·둘을 섞은 표기를 **한 갈래로** 받는다.
    # 페이로드를 컨테이너 경계로 자르고, 자산인지는 `sniff_asset()` 이 판단한다.
    # 최소 길이를 요구하지 않는다 — 종전의 16자 하한은 「첫 리터럴 공백이 16자 안에
    # 오느냐」라는 **표기의 우연**이 탐지를 가르는 두 번째 자리였다. 후보 수가 `data:`
    # 등장 수로 묶여 있어 디코드 비용은 하한 없이도 작고, 짧은 조각은 스니핑이 걸러낸다.
    unterminated: dict[str, int] = {}
    for scheme, body in _data_uri_bodies(text):
        if _B64_META_TAIL_RE.search(text[scheme : body - 1]):
            continue  # base64 판이 이미 봤다
        end = _payload_end(text, scheme, body, unterminated)
        if end < 0 or end <= body:
            continue
        # URL 파서가 URL 전체에서 지우는 3종만 벗긴다 — SPACE·FF 는 내용이다 (위 「공백 처리」).
        payload = strip_chars(text[body:end], URL_STRIP_CHARS)
        if not payload:
            continue
        # 예외를 삼키지 않는다 — `text` 는 `entry.data.decode("utf-8")`(strict)의 산출물이라
        # 서로게이트가 없고, `unquote_to_bytes` 는 그런 입력에 예외를 던지지 않는다. 종전의
        # `except (UnicodeError, ValueError): continue` 는 죽은 가지였고(리뷰가 두 번 지적),
        # 죽은 가지를 남겨 두면 나중에 진짜 예외가 조용히 삼켜진다.
        add(
            scheme,
            "data: URI (퍼센트·원문 본문)",
            urllib.parse.unquote_to_bytes(payload),
        )
    # 컨테이너가 없는 자리(산문 등)의 원문 SVG 백스톱 — 위 갈래는 그런 자리에서 SPACE·`>`
    # 에서 끊기므로 `<svg` 를 앵커로 다시 본다. 브라우저는 이 표기를 되살리지 못하지만
    # (따옴표 없는 URL 토큰은 공백에서 끝난다) 과검출은 릴리스를 **멈추는** 방향이라 남긴다.
    # 종결을 닫는 태그로 찾으므로 공백·`>` 로 끊기지 않는다.
    for match in SVG_TEXT_OPEN_RE.finditer(text):
        if match.start() == 0 or text[match.start() - 1] != ",":
            continue
        scheme = _data_scheme_start(text, match.start() - 1)
        if scheme is None:
            continue
        close = SVG_TEXT_CLOSE_RE.search(text, match.start())
        if close is None:
            continue
        add(
            scheme,
            "data: URI (인코딩 없는 SVG)",
            urllib.parse.unquote_to_bytes(text[match.start() : close.end()]),
        )
    for match in BARE_B64_RE.finditer(text):
        # **정렬 검증** — 앵커는 런의 아무 위치에서나 매치될 수 있다(finditer 는 어디서든
        # 시작한다). 런 중간에서 시작하면 base64 정렬이 어긋나 디코드 결과가 쓰레기 바이트가
        # 되고, 그게 「바이너리」로 판정돼 오탐이 된다 (긴 base64 문자열이면 무엇이든 — 무결성
        # 해시·인증서 픽스처·소스맵 — 안에 `AAAB` 같은 앵커가 우연히 들어간다).
        # D2 의 전제는 「이 런이 자산 매직으로 **시작한다**」이므로, 디코드 결과가 실제로
        # 그 매직으로 시작할 때만 받는다. 아니면 정렬이 어긋난 것이니 버린다.
        data = _decode_b64(match.group(0), minimum=MIN_BARE_B64_RUN_CHARS)
        if data is None or sniff_magic(data) is None:
            continue
        add(match.start(), "감싸개 없는 base64 런", data)
    return found


def has_size_threshold(kind: str) -> bool:
    """규칙 B 의 바이트 문턱이 이 자산 종류에 근거를 갖는가 (#406 ② 재수정, PR #409 리뷰).

    문턱의 근거(독스트링 「인라인 자산」 절)는 명시적으로 **래스터** 한정이다 — 「1 KiB 미만
    래스터에는 알아볼 수 있는 제3자 아트워크가 안 들어간다」. **벡터는 바이트 수와 시각적
    식별성이 비례하지 않아** 그 근거가 성립하지 않는다 (리뷰 실측: 널리 알려진 상표 로고를
    path 하나로 511 B / data URI 703 B 에 담아 문턱 아래로 통과시켰다).

    그래서 벡터에는 문턱을 걸지 않는다. 이것은 새 규칙이 아니라 **(3)이 `.svg` **파일**에 이미
    적용하던 규칙을 조각 단위로 내린 것**이다 — `ASSET_EXTENSIONS` 는 `.svg` 를 크기와 무관하게
    출처 등록 대상으로 삼는다. 문턱을 벡터에도 걸던 쪽이 (3)과 어긋난 예외였다.

    **면제는 `sniff_asset()` 이 벡터로 알아본 것에만 걸린다** (PR #409 3라운드). 못 알아본
    조각은 「바이너리 (매직 넘버 미상)」로 떨어져 **래스터 문턱을 다시 받는다** — 68 B SVG
    아이콘을 UTF-16 으로 인코딩하면 138 B 인데 UTF-8 로 안 읽혀 그 자리에 걸렸고, 문턱 아래라
    통과했다 (실측). 그 인코딩 계열은 `_svg_marker_found()` 가 받게 고쳤지만, **「문턱이 없다」는
    보장이 스니핑의 성공에 종속된다는 성질 자체는 남는다.** 스니핑이 못 알아본 1 KiB 미만
    조각은 통과한다 — 모듈 독스트링 「못 막는 것」에 적었다.

    **잔여 비대칭 — 매직 표의 비래스터 항목.** 위 근거는 래스터 한정인데 이 함수는 폰트·PDF·
    미디어·ZIP 에도 문턱을 건다. 근거가 그쪽까지 덮지는 않지만 이번 라운드에서는 바꾸지
    않았다 — 「매직 미상 바이너리」와 함께 문턱을 걷어내면 오탐이 얼마나 늘지 현재 트리로는
    잴 수 없기 때문이다 (디코드에 성공하는 조각이 1건뿐이다). 별건으로 남긴다.
    """
    return kind != SVG_ASSET_KIND


def check_inline_assets(entry: Entry, text: str) -> list[str]:
    """규칙 A(denylist·문턱 없음) + 규칙 B(미등록 자산·래스터만 문턱)를 인라인 조각에 적용한다."""
    violations: list[str] = []
    for line, detector, data in find_inline_assets(text):
        sha = blob_sha(data)
        kind = sniff_asset(data)
        if sha in DENYLIST_BLOBS:
            violations.append(
                f"{entry.path}:{line}: 제거 대상 blob 이 인라인으로 재유입 — "
                f"{DENYLIST_BLOBS[sha]} (blob {sha[:8]}, {len(data)}B, {detector})"
            )
            continue
        if kind is None:
            continue
        if has_size_threshold(kind) and len(data) < INLINE_ASSET_MIN_BYTES:
            continue
        if sha in INLINE_ASSET_ALLOWLIST:
            continue
        threshold = "" if has_size_threshold(kind) else " (벡터 — 문턱 없음)"
        violations.append(
            f"{entry.path}:{line}: 출처 미등록 인라인 자산 — {kind} "
            f"{len(data)}B{threshold} (blob {sha[:8]}, {detector}) — INLINE_ASSET_ALLOWLIST 에 "
            f"해시·출처를 등록하거나 공개본에서 빼라"
        )
    return violations


def check(entries: list[Entry]) -> tuple[list[str], dict[str, int], list[str]]:
    """위반 목록, 검사 건수, 「출처 미검증」 통지 목록을 돌려준다."""
    violations: list[str] = []
    notices: list[str] = []
    by_path = {entry.path: entry for entry in entries}
    allow_by_path = {path: (sha, why, ok) for path, sha, why, ok in ASSET_ALLOWLIST}

    # (1) 제거 대상 blob 재유입
    for entry in entries:
        if entry.sha in DENYLIST_BLOBS:
            violations.append(
                f"{entry.path}: 제거 대상 blob 재유입 — {DENYLIST_BLOBS[entry.sha]} (blob {entry.sha[:8]})"
            )

    # (2) 자격증명 — 경로
    for entry in entries:
        for pattern, why in SECRET_PATH_RULES:
            if pattern.search(entry.path):
                violations.append(f"{entry.path}: 공개 금지 경로 — {why}")

    # (2) 자격증명 — 내용 · (5) 인라인 자산 — 같은 순회에서 본다 (디코드 비용 절약)
    content_scanned = 0
    inline_scanned = 0
    for entry in entries:
        if not is_text(entry.data):
            continue
        text = entry.data.decode("utf-8")

        # (5) 인라인 자산 — 검사기 자신도 예외로 두지 않는다 (독스트링 「못 막는 것」)
        inline_scanned += 1
        violations.extend(check_inline_assets(entry, text))

        if SECRET_CONTENT_SKIP.search(entry.path):
            continue
        content_scanned += 1
        for pattern, why in SECRET_CONTENT_RULES:
            match = pattern.search(text)
            if match:
                line = text.count("\n", 0, match.start()) + 1
                violations.append(f"{entry.path}:{line}: 시크릿 패턴 — {why}")

    # (3) 자산 출처 등록
    assets = [
        entry for entry in entries if not is_text(entry.data) or Path(entry.path).suffix.lower() in ASSET_EXTENSIONS
    ]
    for entry in assets:
        registered = allow_by_path.get(entry.path)
        if registered is None:
            violations.append(
                f"{entry.path}: 출처 미등록 자산 (blob {entry.sha[:8]}) — "
                "ASSET_ALLOWLIST 에 경로·해시·출처를 등록하거나 공개본에서 빼라"
            )
            continue
        expected_sha, why, verified = registered
        if entry.sha != expected_sha:
            violations.append(
                f"{entry.path}: 등록된 자산의 내용이 바뀌었다 "
                f"(등록 {expected_sha[:8]} → 현재 {entry.sha[:8]}) — 새 출처를 확인하고 갱신하라"
            )
            continue
        if not verified:
            notices.append(f"{entry.path} — {why}")

    # (3) fail-closed: 낡은 등록 (등록돼 있는데 트리에 없다)
    for path, _sha, _why, _verified in ASSET_ALLOWLIST:
        if path not in by_path:
            violations.append(
                f"{path}: ASSET_ALLOWLIST 에 등록됐으나 트리에 없다 — 낡은 등록은 "
                "같은 경로로 들어올 다음 파일에 통과를 내준다. 등록을 지워라"
            )

    # (4) 필수 파일
    for required in REQUIRED_FILES:
        if required not in by_path:
            violations.append(f"{required}: 공개 배포 필수 파일이 트리에 없다")

    counts = {
        "files": len(entries),
        "content_scanned": content_scanned,
        "inline_scanned": inline_scanned,
        "assets": len(assets),
        "denylist_blobs": len(DENYLIST_BLOBS),
        "allowlist_entries": len(ASSET_ALLOWLIST),
        "secret_path_rules": len(SECRET_PATH_RULES),
        "secret_content_rules": len(SECRET_CONTENT_RULES),
        "inline_magics": len(ASSET_MAGICS),
        "inline_anchors": len(_INLINE_B64_ANCHORS),
    }
    return violations, counts, notices


def run(entries: list[Entry], symlinks: int, source_label: str) -> int:
    if len(entries) < MIN_TRACKED_FILES:
        print(
            f"공개 배포 트리 게이트 실패: 대상 파일 {len(entries)}개 "
            f"(하한 {MIN_TRACKED_FILES}) — 대상 지정이 현실과 어긋났다 [{source_label}]"
        )
        return 1

    violations, counts, notices = check(entries)

    # fail-closed — 「아무것도 안 봤음」이 초록으로 새지 않게 (전역 「회귀 그물은 fail-closed 로」)
    for label, value in (
        ("인라인 스캔 대상 텍스트 파일", counts["inline_scanned"]),
        ("자산 매직 넘버 표", counts["inline_magics"]),
        ("D2 base64 앵커", counts["inline_anchors"]),
    ):
        if value == 0:
            print(f"공개 배포 트리 게이트 실패: {label} 0건 — 검사가 존재하지 않는 상태다 [{source_label}]")
            return 1

    summary = (
        f"파일 {counts['files']} (내용 스캔 {counts['content_scanned']} · "
        f"인라인 스캔 {counts['inline_scanned']} · 심링크 {symlinks} 검사 제외) · "
        f"자산 {counts['assets']}/등록 {counts['allowlist_entries']} · "
        f"금지 blob {counts['denylist_blobs']}종 · "
        f"경로규칙 {counts['secret_path_rules']}·내용규칙 {counts['secret_content_rules']} · "
        f"인라인 매직 {counts['inline_magics']}/앵커 {counts['inline_anchors']}"
        f" (문턱 {INLINE_ASSET_MIN_BYTES}B, 등록 {len(INLINE_ASSET_ALLOWLIST)})"
    )

    if notices:
        print(f"⚠ 출처 미검증 자산 {len(notices)}건 — 공개 전에 사람이 확인한다:")
        for notice in notices:
            print(f"  - {notice}")

    if violations:
        print(f"공개 배포 트리 위반 {len(violations)}건 [{source_label}] — {summary}:")
        for violation in violations:
            print(f"  - {violation}")
        print("공개 push 는 되돌릴 수 없다. 위반을 해소하기 전에는 내보내지 않는다 (#360).")
        return 1

    print(f"공개 배포 트리 통과 [{source_label}] — {summary}, 위반 0건")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ref", default="HEAD", help="검사할 git ref (기본 HEAD)")
    parser.add_argument(
        "--tree",
        type=Path,
        help="git 이 아닌 디렉터리 트리를 직접 검사 (내보내기 스테이징)",
    )
    parser.add_argument("--repo", type=Path, default=REPO_ROOT, help="git 레포 경로")
    args = parser.parse_args(argv)

    if args.tree is not None:
        if not args.tree.is_dir():
            print(f"공개 배포 트리 게이트 실패: --tree 경로가 없다 ({args.tree})")
            return 1
        entries, symlinks = collect_from_tree(args.tree)
        return run(entries, symlinks, f"tree {args.tree}")
    entries, symlinks = collect_from_ref(args.repo, args.ref)
    return run(entries, symlinks, f"{args.repo.name}@{args.ref}")


if __name__ == "__main__":
    sys.exit(main())
