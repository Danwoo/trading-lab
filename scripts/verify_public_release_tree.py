class Entry:
    """트리의 파일 하나 — 경로, blob 해시, 내용 (지연 로드)."""

    __slots__ = ("path", "sha", "_data")

    def __init__(self, path: str, sha: str, data: bytes) -> None:
        self.path = path
        self.sha = sha
        self._data = data

    @property
    def data(self) -> bytes:
        return self._data


def blob_sha(data: bytes) -> str:
    """git 의 blob object id — `git hash-object` 와 같은 값 (git 실행 없이)."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


def collect_from_ref(repo: Path, ref: str) -> tuple[list[Entry], int]:
    """(일반 파일 엔트리, 건너뛴 심링크 수). 심링크는 내용이 없어 검사 대상이 아니다."""
    listing = subprocess.run(
        ["git", "-C", str(repo), "ls-tree", "-r", "-z", ref],
        capture_output=True,
        check=True,
    ).stdout.decode("utf-8")
    entries: list[Entry] = []
    symlinks = 0
    for record in listing.split("\0"):
        if not record:
            continue
        meta, path = record.split("\t", 1)
        mode, obj_type, sha = meta.split()
        if obj_type != "blob":  # 서브모듈(commit) 등은 파일이 아니다
            continue
        if mode == "120000":  # 심링크 — 내용은 대상 경로 문자열
            symlinks += 1
            continue
        data = subprocess.run(
            ["git", "-C", str(repo), "cat-file", "blob", sha],
            capture_output=True,
            check=True,
        ).stdout
        entries.append(Entry(path, sha, data))
    return entries, symlinks


def collect_from_tree(root: Path) -> tuple[list[Entry], int]:
    entries: list[Entry] = []
    symlinks = 0
    for path in sorted(root.rglob("*")):
        if ".git" in path.relative_to(root).parts:
            continue
        if path.is_symlink():
            symlinks += 1
            continue
        if not path.is_file():
            continue
        data = path.read_bytes()
        entries.append(Entry(path.relative_to(root).as_posix(), blob_sha(data), data))
    return entries, symlinks


def is_text(data: bytes) -> bool:
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return False
    return True


