def _b64_anchor(magic: bytes) -> str:
    """매직 넘버가 파일 선두에 있을 때 **확정되는** base64 접두사.

    base64 는 3바이트 → 4글자로 대응하므로, 완결된 3바이트 블록만큼은 뒤 내용과 무관하게
    글자가 고정된다. 손으로 옮겨 적으면 틀리므로 유도한다 (PNG → `iVBORw0K`).
    """
    return base64.b64encode(magic).decode("ascii")[: len(magic) // 3 * 4]


